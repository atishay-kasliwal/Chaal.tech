/**
 * Phase 4 report: docs/archive/bots/PHASE4_REPORT.md from the stage results in .sim/phase4/.
 *   node scripts/sim/phase4-report.mjs [--seed 44] [--final 45]
 * Sections whose stage has not run are left out. The summary and recommendations are written by a
 * reviewer into the <!-- ANSWERS --> marker; everything else is generated.
 */
import { readFileSync, existsSync, writeFileSync, readdirSync } from 'node:fs';
import { SHORT, CHAMPIONS } from '../../server/sim/league.mjs';
import { EXPLOITS } from '../../server/sim/adversary.mjs';
import { CHARACTER_IDS } from '../../src/lib/bots/cast.js';
import { STRENGTH_BUCKETS } from '../../server/sim/fingerprint.mjs';

const args = process.argv.slice(2);
const opt = (n, d) => (args.includes(`--${n}`) ? args[args.indexOf(`--${n}`) + 1] : d);
const SEED = opt('seed', '44');
const FINAL = opt('final', null);
const DIR = '.sim/phase4';
const load = (name) =>
	existsSync(`${DIR}/${name}.json`)
		? JSON.parse(readFileSync(`${DIR}/${name}.json`, 'utf8'))
		: null;
const champions = JSON.parse(readFileSync('docs/bots/phase4/champions.json', 'utf8'));

const r0 = (x) =>
	x == null || !Number.isFinite(x) ? 'n/a' : `${x >= 0 ? '+' : ''}${Math.round(x)}`;
const pm = (c) => (c ? `${r0(c.mean)} ± ${Math.round(c.ci)}` : 'n/a');
const pct = (x, d = 1) => (x == null || !Number.isFinite(x) ? 'n/a' : `${(100 * x).toFixed(d)}%`);
const f2 = (x) => (x == null || !Number.isFinite(x) ? 'n/a' : x.toFixed(2));
const f3 = (x) => (x == null || !Number.isFinite(x) ? 'n/a' : x.toFixed(3));
const name = (key) => {
	for (const c of CHARACTER_IDS) if (CHAMPIONS[c] === key) return `${SHORT[c]} (champion)`;
	return key;
};
const sig = (c) => (c && Math.abs(c.mean) > c.ci ? '**' : '');
const table = (head, rows) =>
	[
		`| ${head.join(' | ')} |`,
		`|${head.map((h, i) => (i ? '---:' : '---')).join('|')}|`,
		...rows.map((r) => `| ${r.join(' | ')} |`)
	].join('\n');

const totals = { hands: 0, decisions: 0, seconds: 0, maxRssMb: 0 };
const files = readdirSync(DIR).filter((f) => f.endsWith('.json'));
for (const f of files) {
	const d = JSON.parse(readFileSync(`${DIR}/${f}`, 'utf8'));
	if (!d.totals) continue;
	totals.hands += d.totals.hands;
	totals.decisions += d.totals.decisions;
	totals.seconds += d.totals.seconds;
	totals.maxRssMb = Math.max(totals.maxRssMb, d.totals.maxRssMb);
}

const out = [];
out.push(`# Bot Brain Phase 4 report: exploits, adaptation and robustness

Generated by \`node scripts/sim/phase4-report.mjs --seed ${SEED}${FINAL ? ` --final ${FINAL}` : ''}\` on ${new Date().toISOString().slice(0, 10)} from \`.sim/phase4/\` (copied to \`docs/bots/phase4/\`). Real engine, ${champions.versions.sim}, ${champions.versions.fingerprint}, ${champions.versions.judge}, ${champions.versions.targets}, ${champions.versions.adversary}. Boot 10, stack 100 boots, automatic rebuys. Every comparison is matched: the same decks, seats, opponents and per-seat decision streams; only the bot under study changes. Intervals are 95%, over independent tables or nights. **Nothing here is published or adopted.**

<!-- ANSWERS -->
`);

/* 1. Champions */
out.push(`## 1. The champions (frozen)

Baseline \`${champions.baselineTag}\` = \`${champions.baselineCommit.slice(0, 12)}\`, frozen ${champions.frozen} in \`docs/bots/phase4/champions.json\`; \`tests/server/bot-phase4.test.mjs\` fails if any of these changes.

${table(
	['character', 'style', 'policy', 'mind', 'config hash', 'quirks'],
	CHARACTER_IDS.map((c) => {
		const x = champions.champions[c];
		return [
			SHORT[c],
			`\`${x.style}\``,
			x.policy,
			x.mind,
			`\`${x.configHash}\``,
			x.quirks.map((q) => `${q.id} ${q.strength}`).join(', ')
		];
	})
)}
`);

/* 2. Calibration */
const cal = load(`calibration-${SEED}`);
if (cal) {
	const rows = [];
	for (const c of CHARACTER_IDS)
		for (const [type, r] of Object.entries(cal.strength[c]))
			rows.push([
				SHORT[c],
				type,
				...[50, 100, 200].map(
					(L) => `${Math.round(r[L].sdPaired)} / ${Math.round(r[L].sdUnpaired)}`
				),
				...[50, 200].map((L) => `${Math.round(r[L].hands100 / 1000)}k`),
				r[100].gapSd != null ? `${Math.round(r[100].gapSd)}` : ''
			]);
	out.push(`## 2. Measurement calibration (seed ${cal.seed}: ${cal.tables} tables per cell, ${cal.nights} nights per character)

Before any bot was changed: how noisy is each measurement, and how much play makes it useful? Each champion was paired with a realistic challenger (a historical candidate). The spread is per table, of boots/100 for one table, in sessions of 50, 100 and 200 hands. "Hands for ±100" is the play one comparison needs for a 95% interval of ±100 boots/100 on a champion−challenger difference.

${table(['character', 'opponents', 'paired / unpaired spread, 50 hands', '100 hands', '200 hands', 'hands for ±100 (50-hand sessions)', '(200-hand sessions)', 'exploit gap spread (100 hands)'], rows)}

**What this decided.** Paired (matched) play cuts the spread by a third to two thirds. Shorter sessions are far more efficient per hand: a small difference in play compounds through a long session (stacks diverge), so the same 200 hands as four 50-hand sessions measure a difference 3 to 8 times more precisely. Strength comparisons in Phase 4 therefore use many short sessions (100 hands; 50 where no session effect is studied), and only adaptation studies keep 200-hand sessions. Against calling stations and maniacs the spread is so large that a ±100 interval needs 0.2 to 1.8 million hands per comparison: those intervals are reported as measured, and never treated as decisive. An exploit gap compares the champion with a different player (the reference), so it cannot be paired and is the noisiest measure of all.

### Night-to-night variety: how many nights?

${table(
	['character', 'variety (all nights)', 'error at 12 nights', '25', '50', '100'],
	CHARACTER_IDS.map((c) => {
		const n = cal.night[c];
		return [
			SHORT[c],
			f2(n.full),
			...[12, 25, 50, 100].map((k) =>
				n.byK[k] ? `± ${f2(1.96 * n.byK[k].sd)} (${pct(n.byK[k].relSd, 0)})` : ''
			)
		];
	})
)}

The Phase 3.1 gate used 12 nights: one estimate there carried a relative error of 17 to 42%, too much to tell a candidate from its ancestor (that gate could not have protected the floor it set). Phase 4 screens with 50 nights or more and judges finalists on 80 to 100.
`);
}

