/**
 * Offline generator for server/analytics/intel/holdem-equity.mjs: heads-up preflop equity of each of
 * the 169 starting-hand classes against one random hand, by seeded Monte Carlo with the engine's own
 * evaluator. Deterministic (fixed seed), committed, never run on a request (Workers CPU).
 *   node scripts/generate-holdem-equity.mjs [trials]
 */
import { writeFileSync } from 'node:fs';
import { evaluateBestHand, compareScores } from '../server/poker/holdem.mjs';

const trials = Number(process.argv[2] ?? 4000);
const SUITS = ['hearts', 'diamonds', 'clubs', 'spades'];
const LETTER = { 14: 'A', 13: 'K', 12: 'Q', 11: 'J', 10: 'T' };
const letter = (r) => LETTER[r] ?? String(r);
function mulberry(seed) {
	let a = seed >>> 0;
	return () => {
		a = (a + 0x6d2b79f5) >>> 0;
		let t = a;
		t = Math.imul(t ^ (t >>> 15), t | 1);
		t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
		return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
	};
}
const deck = SUITS.flatMap((suit) => Array.from({ length: 13 }, (_, i) => ({ rank: i + 2, suit })));
const key = (c) => `${c.rank}:${c.suit}`;

const out = {};
let seed = 20260101;
for (let hi = 14; hi >= 2; hi--)
	for (let lo = hi; lo >= 2; lo--)
		for (const kind of hi === lo ? ['p'] : ['s', 'o']) {
			const hole = kind === 's' ? [{ rank: hi, suit: 'spades' }, { rank: lo, suit: 'spades' }] : [{ rank: hi, suit: 'spades' }, { rank: lo, suit: kind === 'p' ? 'hearts' : 'hearts' }];
			const taken = new Set(hole.map(key));
			const rest = deck.filter((c) => !taken.has(key(c)));
			const random = mulberry(seed++);
			let score = 0;
			for (let t = 0; t < trials; t++) {
				// partial Fisher-Yates: 2 opponent cards + 5 board
				for (let i = 0; i < 7; i++) {
					const j = i + Math.floor(random() * (rest.length - i));
					[rest[i], rest[j]] = [rest[j], rest[i]];
				}
				const board = rest.slice(2, 7);
				const cmp = compareScores(evaluateBestHand([...hole, ...board]), evaluateBestHand([rest[0], rest[1], ...board]));
				score += cmp > 0 ? 1 : cmp === 0 ? 0.5 : 0;
			}
			out[`${letter(hi)}${letter(lo)}${kind}`] = Math.round((score / trials) * 1000) / 1000;
		}
writeFileSync(
	new URL('../server/analytics/intel/holdem-equity.mjs', import.meta.url),
	`/** Generated by scripts/generate-holdem-equity.mjs (seeded Monte Carlo, ${trials} deals per class). Do not edit.\n * Heads-up preflop equity against one random hand, ties counted half. Standard error about ±0.7 points. */\nexport const HOLDEM_EQUITY = Object.freeze(${JSON.stringify(out, null, '\t')});\nexport const HOLDEM_EQUITY_TRIALS = ${trials};\n`
);
console.log(`wrote ${Object.keys(out).length} classes`);
