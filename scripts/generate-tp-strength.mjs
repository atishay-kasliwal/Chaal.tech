/**
 * Offline generator for server/analytics/intel/tp-strength.mjs: for every Teen Patti variant whose hand
 * strength depends only on the cards themselves, every distinct hand value with the share of all
 * possible hands that are strictly weaker and the share that tie. Deterministic and exact (it
 * enumerates every hand). Run after adding a variant:   node scripts/generate-tp-strength.mjs
 * A test fails if a supported variant has no table.
 */
import { writeFileSync } from 'node:fs';
import { listVariants } from '../server/variants/index.mjs';
import { strengthModelFor } from '../server/analytics/intel/strength.mjs';

const SUITS = ['hearts', 'diamonds', 'clubs', 'spades'];
const DECK = SUITS.flatMap((suit) => Array.from({ length: 13 }, (_, i) => ({ rank: i + 2, suit })));
const out = {};
for (const v of listVariants()) {
	const model = strengthModelFor(v.rulesVersion);
	if (!model) continue;
	const groups = new Map();
	const walk = (start, picked) => {
		if (picked.length === model.k) {
			const key = model.variant.evaluateHand(picked).join(',');
			const g = groups.get(key) ?? { key, count: 0, sample: [...picked] };
			g.count++;
			groups.set(key, g);
			return;
		}
		for (let i = start; i < DECK.length; i++) walk(i + 1, [...picked, DECK[i]]);
	};
	walk(0, []);
	const ordered = [...groups.values()].sort((a, b) => model.variant.compareHands(a.sample, b.sample));
	const total = ordered.reduce((s, g) => s + g.count, 0);
	let below = 0;
	out[v.rulesVersion] = ordered.map((g) => {
		const row = [g.key, Math.round((below / total) * 1e9) / 1e9, Math.round((g.count / total) * 1e9) / 1e9];
		below += g.count;
		return row;
	});
	console.log(v.rulesVersion, ordered.length, 'distinct hand values');
}
const body = Object.entries(out).map(([k, rows]) => `\t${JSON.stringify(k)}: [\n${rows.map((r) => `\t\t${JSON.stringify(r)}`).join(',\n')}\n\t]`).join(',\n');
writeFileSync(new URL('../server/analytics/intel/tp-strength.mjs', import.meta.url), `/** Generated by scripts/generate-tp-strength.mjs. Do not edit. [hand value, share strictly weaker, share tied]. */\nexport const TP_STRENGTH = Object.freeze({\n${body}\n});\n`);
